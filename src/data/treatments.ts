export function getTreatment(slug: TreatmentSlug): Treatment {
	const treatment = TREATMENTS.find((t) => t.slug === slug);
	if (!treatment) throw new Error(`Unknown treatment slug: ${slug}`);
	return treatment;
}

/**
 * 한의원이 운영하는 전체 모달리티 (중복 제거).
 * 진료과목 허브 페이지의 "전체 진료 방법" 그리드에 사용.
 */
export function getAllModalities(): readonly Modality[] {
	const seen = new Set<string>();
	const all: Modality[] = [];
	for (const t of TREATMENTS) {
		for (const m of t.modalities) {
			if (seen.has(m.title)) continue;
			seen.add(m.title);
			all.push(m);
		}
	}
	// 한의원 전반 케어용으로 안마의자 추가 (자동차보험 환자 보조 케어).
	if (!seen.has(MOD.massage.title)) {
		all.push(MOD.massage);
	}
	return all;
}
